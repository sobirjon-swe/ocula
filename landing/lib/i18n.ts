export function isLocale(value:string): value is Locale { return (locales as readonly string[]).includes(value) }
export function getCopy(locale:Locale): Copy { return locale==='uz-cyrl' ? Object.fromEntries(Object.entries(uz).map(([key,value])=>[key,toCyrillic(value)])) as Copy : locale==='ru'?ru:locale==='en'?en:uz }
